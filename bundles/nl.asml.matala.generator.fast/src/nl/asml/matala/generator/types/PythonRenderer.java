package nl.asml.matala.generator.types;

import java.util.*;

/** Deterministic Python emission, independent of Eclipse and Xtext. */
public final class PythonRenderer {
	public static final Set<String> HELPERS = Set.of("F", "L", "FileSelector", "Ref", "RefList", "Template");
	public static final Set<String> KEYWORDS = Set.of("False", "None", "True", "and", "as", "assert", "async", "await",
			"break", "class", "continue", "def", "del", "elif", "else", "except", "finally", "for", "from", "global",
			"if", "import", "in", "is", "lambda", "nonlocal", "not", "or", "pass", "raise", "return", "try", "while",
			"with", "yield");
	public static final Set<String> GLOBALS = Set.of("F", "L", "FileSelector", "Model", "Ref", "RefList", "Template",
			"StrEnum", "list", "dict", "str", "int", "float", "bool");

	public static String identifier(String name) {
		if (name == null || !name.matches("[A-Za-z][A-Za-z0-9_]*") || KEYWORDS.contains(name))
			throw new IllegalArgumentException("Invalid Python identifier: " + name);
		return name;
	}

	public String render(Schema schema) {
		Map<String, Schema.Declaration> types = new LinkedHashMap<>();
		for (var d : schema.declarations()) {
			identifier(d.name());
			if (GLOBALS.contains(d.name()) || types.putIfAbsent(d.name(), d) != null)
				throw new IllegalArgumentException("Duplicate/reserved type: " + d.name());
		}
		StringBuilder out = new StringBuilder(
				"# Generated by typesToPython. Do not edit.\n"
				+ "from __future__ import annotations\n\n"
				+ "from enum import StrEnum\n"
				+ "from .ui_api import F, L, FileSelector, Model, Ref, RefList, Template\n");
		Set<String> emitted = new HashSet<>();
		for (var d : types.values())
			if (!d.literals().isEmpty()) {
				out.append("\n\nclass ").append(d.name()).append("(StrEnum):\n");
				Set<String> seen = new HashSet<>();
				for (String member : d.literals()) {
					identifier(member);
					if (!seen.add(member))
						throw new IllegalArgumentException("Duplicate enum member: " + member);
					Object value = d.metadata().getOrDefault("value_" + member, member);
					if (!(value instanceof String))
						throw new IllegalArgumentException("Enum value must be a string");
					out.append("    ").append(member).append(" = ").append(PythonValues.literal(value)).append('\n');
				}
				emitted.add(d.name());
			}
		for (var d : types.values())
			if (d.base() != null)
				alias(d, types, emitted, new HashSet<>(), out);
		for (var d : types.values())
			if (record(d)) {
				out.append("\n\nclass ").append(d.name()).append("(Model):\n");
				if (d.fields().isEmpty())
					out.append("    pass\n");
				Set<String> seen = new HashSet<>();
				for (var f : d.fields()) {
					identifier(f.name());
					if (!seen.add(f.name()) || GLOBALS.contains(f.name()))
						throw new IllegalArgumentException("Duplicate/reserved field: " + f.name());
					String type = type(f.type(), types);
					var meta = new LinkedHashMap<>(f.metadata());
					String helper = f.helper() == null ? (type.startsWith("list[") ? "L" : "F") : f.helper();
					if (!HELPERS.contains(helper))
						throw new IllegalArgumentException("Unsupported helper: " + helper);
					if (Set.of("L", "RefList").contains(helper) && !type.startsWith("list["))
						throw new IllegalArgumentException(helper + " requires a list: " + f.name());
					if (Set.of("Ref", "FileSelector", "Template").contains(helper) && !type.equals("str"))
						throw new IllegalArgumentException(helper + " requires string: " + f.name());
					if (meta.containsKey("default") && meta.containsKey("default_factory"))
						throw new IllegalArgumentException("Conflicting defaults: " + f.name());
					for (String key : meta.keySet())
						identifier(key);
					if (meta.containsKey("required") && !(meta.get("required") instanceof Boolean))
						throw new IllegalArgumentException("required must be boolean");
					for (String key : List.of("filters", "items", "relevant_if", "required_if"))
						if (meta.containsKey(key) && !(meta.get(key) instanceof Map))
							throw new IllegalArgumentException(key + " must be an object");
					if (meta.containsKey("predefined") && !(meta.get("predefined") instanceof List))
						throw new IllegalArgumentException("predefined must be a list");
					if (meta.get("ge") instanceof Number low && meta.get("le") instanceof Number high
							&& low.doubleValue() > high.doubleValue())
						throw new IllegalArgumentException("ge must not exceed le");
					if (helper.equals("RefList") && !type.equals("list[str]"))
						throw new IllegalArgumentException("RefList requires string items");
					if (meta.containsKey("default") && meta.get("default") == null)
						type += " | None";
					out.append("    ").append(f.name()).append(": ").append(type).append(" = ").append(helper)
							.append("(\n");
					if (helper.equals("Ref") || helper.equals("RefList")) {
						Object path = meta.remove("path");
						if (!(path instanceof String s) || s.isBlank())
							throw new IllegalArgumentException("Reference path required: " + f.name());
						out.append("        ").append(PythonValues.literal(path)).append(",\n");
					}
					if (!meta.containsKey("default") && !meta.containsKey("default_factory")) {
						if (Boolean.TRUE.equals(meta.get("required")))
							meta.put("default", Required.VALUE);
						else if (types.containsKey(f.type()) && record(types.get(f.type()))) {
							cycle(f.type(), types, new HashSet<>());
							meta.put("default_factory", f.type());
						} else if (helper.equals("F"))
							meta.put("default", switch (type) {
							case "str" -> "";
							case "int" -> 0;
							case "float" -> 0.0;
							case "bool" -> false;
							default -> Required.VALUE;
							});
					}
					for (var entry : meta.entrySet()) {
						String value;
						if (entry.getKey().equals("default_factory")) {
							String factory = String.valueOf(entry.getValue());
							if (!Set.of("list", "dict").contains(factory) && !types.containsKey(factory))
								throw new IllegalArgumentException("Unknown factory: " + factory);
							value = "lambda: " + identifier(factory) + "()";
						} else
							value = entry.getValue() == Required.VALUE ? "..." : PythonValues.literal(entry.getValue());
						out.append("        ").append(entry.getKey()).append("=").append(value).append(",\n");
					}
					out.append("    )\n");
				}
			}
		return out.toString();
	}

	private enum Required {
		VALUE
	}

	private static boolean record(Schema.Declaration d) {
		return d.base() == null && d.literals().isEmpty();
	}

	private void cycle(String name, Map<String, Schema.Declaration> types, Set<String> visiting) {
		if (!visiting.add(name))
			throw new IllegalArgumentException("Recursive default factories: " + name + "; use default_json=\"null\"");
		for (var f : types.get(name).fields())
			if (types.containsKey(f.type()) && record(types.get(f.type())) && !f.metadata().containsKey("default")
					&& !Boolean.TRUE.equals(f.metadata().get("required")))
				cycle(f.type(), types, visiting);
		visiting.remove(name);
	}

	private void alias(Schema.Declaration d, Map<String, Schema.Declaration> types, Set<String> emitted,
			Set<String> visiting, StringBuilder out) {
		if (emitted.contains(d.name()))
			return;
		if (!visiting.add(d.name()))
			throw new IllegalArgumentException("Cyclic alias: " + d.name());
		var target = types.get(d.base());
		if (target != null && target.base() != null)
			alias(target, types, emitted, visiting, out);
		if (target != null && record(target))
			throw new IllegalArgumentException("Record alias unsupported: " + d.name());
		out.append('\n').append(d.name()).append(" = ").append(type(d.base(), types)).append('\n');
		visiting.remove(d.name());
		emitted.add(d.name());
	}

	/**
	 * Only validated type syntax is emitted; arbitrary source text is never
	 * executed.
	 */
	public String type(String source, Map<String, Schema.Declaration> types) {
		String s = source.replaceAll("\\s+", "");
		if (s.endsWith("[]"))
			return "list[" + type(s.substring(0, s.length() - 2), types) + "]";
		if (s.startsWith("map<") && s.endsWith(">")) {
			String body = s.substring(4, s.length() - 1);
			int depth = 0;
			for (int i = 0; i < body.length(); i++) {
				char c = body.charAt(i);
				if (c == '<')
					depth++;
				if (c == '>')
					depth--;
				if (c == ',' && depth == 0)
					return "dict[" + type(body.substring(0, i), types) + ", " + type(body.substring(i + 1), types)
							+ "]";
			}
			throw new IllegalArgumentException("Invalid map: " + source);
		}
		return switch (s) {
		case "string" -> "str";
		case "int" -> "int";
		case "real" -> "float";
		case "bool" -> "bool";
		default -> {
			if (!types.containsKey(s))
				throw new IllegalArgumentException("Unknown/unsupported type: " + source);
			yield identifier(s);
		}
		};
	}
}
